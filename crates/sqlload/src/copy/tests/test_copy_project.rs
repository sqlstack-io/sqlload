use crate::copy::tests::helpers::{PROJECT, outcome};
use crate::copy::tests::test_types::CopyProjectTestCase;

#[test]
fn given_copy_endpoints_when_building_the_project_then_secrets_stay_out_of_its_text() {
    let test_cases = [
        CopyProjectTestCase {
            description: "a literal URI password becomes a reference with its value kept aside, and a warning",
            source: "postgresql://app:hunter2%40x@db:6543/shop#public.accounts",
            destination: "duckdb://wh.duckdb#RAW.ACCOUNTS",
            project: "",
            expected_lines: &[
                "database = \"wh.duckdb\"",
                "database = \"shop\"",
                "host = \"db\"",
                "password = \"${ENV:SQLLOAD_COPY_SOURCE_PASSWORD}\"",
                "port = 6543",
                "user = \"app\"",
                "description = \"Copied from Postgres table public.accounts.\"",
                "destination = \"copy_accounts\"",
                "include = [\"public.accounts\"]",
                "description = \"Copied from Postgres table public.accounts.\"",
                "name = \"ACCOUNTS\"",
                "loader_schema = \"RAW\"",
                "printed [connections.copy_accounts_destination]",
                "printed [connections.copy_accounts_source]",
                "SQLLOAD_COPY_SOURCE_PASSWORD=hunter2@x",
                "postgresql://app:***@db:6543/shop#public.accounts has a literal password; use ${ENV:NAME} in the URI so it stays out of shell history",
            ],
        },
        CopyProjectTestCase {
            description: "${ENV} works for the user, password and host, and stays a reference with no warning",
            source: "postgresql://${ENV:PGUSER}:${ENV:PG}@${ENV:PGHOST}/shop#public.accounts",
            destination: "./out",
            project: "",
            expected_lines: &[
                "root = \"./out\"",
                "database = \"shop\"",
                "host = \"${ENV:PGHOST}\"",
                "password = \"${ENV:PG}\"",
                "port = 5432",
                "user = \"${ENV:PGUSER}\"",
                "description = \"Copied from Postgres table public.accounts.\"",
                "destination = \"copy_accounts\"",
                "include = [\"public.accounts\"]",
                "description = \"Copied from Postgres table public.accounts.\"",
                "name = \"accounts\"",
                "path = \"{table}/\"",
                "printed [connections.copy_accounts_destination]",
                "printed [connections.copy_accounts_source]",
            ],
        },
        CopyProjectTestCase {
            description: "a password holding ${, # and an IPv6 host: literal, kept out of the text",
            source: "postgresql://app:hunter2${x#y@[::1]:5433/shop#public.accounts",
            destination: "./out",
            project: "",
            expected_lines: &[
                "root = \"./out\"",
                "database = \"shop\"",
                "host = \"::1\"",
                "password = \"${ENV:SQLLOAD_COPY_SOURCE_PASSWORD}\"",
                "port = 5433",
                "user = \"app\"",
                "description = \"Copied from Postgres table public.accounts.\"",
                "destination = \"copy_accounts\"",
                "include = [\"public.accounts\"]",
                "description = \"Copied from Postgres table public.accounts.\"",
                "name = \"accounts\"",
                "path = \"{table}/\"",
                "printed [connections.copy_accounts_destination]",
                "printed [connections.copy_accounts_source]",
                "SQLLOAD_COPY_SOURCE_PASSWORD=hunter2${x#y",
                "postgresql://app:***@[::1]:5433/shop#public.accounts has a literal password; use ${ENV:NAME} in the URI so it stays out of shell history",
            ],
        },
        CopyProjectTestCase {
            description: "named connections stay in sqlload.toml: the printed project leaves them out",
            source: "app:public.orders",
            destination: "s3://lake/raw/?region=eu-west-2",
            project: PROJECT,
            expected_lines: &[
                "database = \"shop\"",
                "host = \"db\"",
                "password = \"${ENV:APP_PASSWORD}\"",
                "user = \"loader\"",
                "bucket = \"lake\"",
                "description = \"Copied from app:public.orders.\"",
                "destination = \"copy_orders\"",
                "include = [\"public.orders\"]",
                "description = \"Copied from app:public.orders.\"",
                "name = \"orders\"",
                "path = \"raw/{table}/\"",
                "printed [connections.copy_orders_destination]",
            ],
        },
        CopyProjectTestCase {
            description: "a Windows path is a folder, not a connection named C",
            source: "C:\\exports\\orders",
            destination: "duckdb://wh.duckdb#RAW.ORDERS",
            project: "",
            expected_lines: &[
                "database = \"wh.duckdb\"",
                "root = 'C:\\exports\\orders'",
                "description = 'Copied from folder C:\\exports\\orders.'",
                "destination = \"copy_orders\"",
                "path = \"\"",
                "table_name = \"ORDERS\"",
                "loader_schema = \"RAW\"",
                "printed [connections.copy_orders_destination]",
                "printed [connections.copy_orders_source]",
            ],
        },
        CopyProjectTestCase {
            description: "a Snowflake URI is refused without echoing its password",
            source: "snowflake://me:hunter2@acct/db#S.T",
            destination: "./out",
            project: "",
            expected_lines: &[
                "the source snowflake://me:***@acct/db#S.T: a Snowflake connection needs auth and a load_method, which a URI does not carry; declare it under [connections] in sqlload.toml and name it, as warehouse:SCHEMA.TABLE",
            ],
        },
        CopyProjectTestCase {
            description: "a misspelt scheme is refused without echoing its password",
            source: "postgress://u:hunter2@h/db#a.b",
            destination: "./out",
            project: "",
            expected_lines: &[
                "the source postgress://u:***@h/db#a.b has the scheme postgress://; use postgresql://, duckdb://, s3://, file:// or a connection named in sqlload.toml",
            ],
        },
        CopyProjectTestCase {
            description: "a URI typed with one slash is refused without echoing its password",
            source: "postgresql:/app:hunter2@db/shop#public.a",
            destination: "./out",
            project: "",
            expected_lines: &[
                "the source postgresql:/app:***@db/shop#public.a looks like a URI with one slash; write postgresql://...",
            ],
        },
        CopyProjectTestCase {
            description: "a URI typed without its scheme is refused without echoing its password",
            source: "app:hunter2@db/shop#a.b",
            destination: "./out",
            project: "",
            expected_lines: &[
                "the source app:***@db/shop#a.b names connection app, which is not in sqlload.toml (it has: none); name one of those, or give a URI such as postgresql://user@host/db#schema.table",
            ],
        },
        CopyProjectTestCase {
            description: "an @ in the table name stays in the table, and a drive path with / is a folder",
            source: "postgresql://u@h/db#s.t@x",
            destination: "C:/data/out",
            project: "",
            expected_lines: &[
                "root = \"C:/data/out\"",
                "database = \"db\"",
                "host = \"h\"",
                "port = 5432",
                "user = \"u\"",
                "description = \"Copied from Postgres table s.t@x.\"",
                "destination = \"copy_t_x\"",
                "include = [\"s.t@x\"]",
                "description = \"Copied from Postgres table s.t@x.\"",
                "name = \"t@x\"",
                "path = \"{table}/\"",
                "printed [connections.copy_t_x_destination]",
                "printed [connections.copy_t_x_source]",
            ],
        },
        CopyProjectTestCase {
            description: "names sqlload.toml already has get a suffix, so a second printed copy can be appended too",
            source: "app:public.orders",
            destination: "./out",
            project: "[connections.app]\nkind = \"postgres\"\nhost = \"db\"\nuser = \"u\"\ndatabase = \"shop\"\n[targets.copy_orders]\nconnection = \"app\"\n",
            expected_lines: &[
                "database = \"shop\"",
                "host = \"db\"",
                "user = \"u\"",
                "root = \"./out\"",
                "description = \"Copied from app:public.orders.\"",
                "destination = \"copy_orders_2\"",
                "include = [\"public.orders\"]",
                "description = \"Copied from app:public.orders.\"",
                "name = \"orders\"",
                "path = \"{table}/\"",
                "printed [connections.copy_orders_2_destination]",
            ],
        },
        CopyProjectTestCase {
            description: "a connection sqlload.toml lacks is refused with the ones it has",
            source: "warehouse:public.orders",
            destination: "duckdb://wh.duckdb#RAW.ORDERS",
            project: PROJECT,
            expected_lines: &[
                "the source warehouse:public.orders names connection warehouse, which is not in sqlload.toml (it has: app); name one of those, or give a URI such as postgresql://user@host/db#schema.table",
            ],
        },
        CopyProjectTestCase {
            description: "a warehouse destination without SCHEMA.TABLE is refused",
            source: "app:public.orders",
            destination: "duckdb://wh.duckdb",
            project: PROJECT,
            expected_lines: &[
                "the destination duckdb://wh.duckdb names no table; end it with SCHEMA.TABLE",
            ],
        },
        CopyProjectTestCase {
            description: "a DuckDB source is refused rather than read some other way",
            source: "duckdb://wh.duckdb#main.orders",
            destination: "./out",
            project: "",
            expected_lines: &[
                "the source duckdb://wh.duckdb#main.orders is a duckdb connection; copy reads Postgres tables and files (s3://, file://, a folder)",
            ],
        },
    ];
    for test_case in test_cases {
        assert_eq!(
            outcome(test_case.source, test_case.destination, test_case.project),
            test_case.expected_lines,
            "{}",
            test_case.description
        );
    }
}
